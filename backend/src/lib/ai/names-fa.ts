/**
 * یکسان‌سازی برای تطبیق: ی/ي، ک/ك، ه/ة، ا/أإآ و حذف اعراب و نیم‌فاصله.
 * (فقط برای مقایسه است؛ خروجی نام دست‌نخورده می‌ماند.)
 */
export function normalizeNameWord(word: string): string {
  return word
    .replace(/[\u064B-\u0652\u0670]/g, "")
    .replace(/[يى]/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/[ةۀ]/g, "ه")
    .replace(/[أإآ]/g, "ا")
    .replace(/\u200c/g, "")
    .trim();
}

